      <li><strong>统计所有相邻字符对的全局频次</strong>：
        <ul>
          <li><code>(e, s)</code>：在 <code>newest</code> (6次) 与 <code>widest</code> (3次) 中出现，共 \(6 + 3 = 9\) 次。</li>
          <li><code>(s, t)</code>：在 <code>newest</code> (6次) 与 <code>widest</code> (3次) 中出现，共 \(6 + 3 = 9\) 次。</li>
          <li><code>(l, o)</code>：在 <code>low</code> (5次) 与 <code>lower</code> (2次) 中出现，共 \(5 + 2 = 7\) 次。</li>
          <li><code>(o, w)</code>：在 <code>low</code> (5次) 与 <code>lower</code> (2次) 中出现，共 \(5 + 2 = 7\) 次。</li>
          <li><code>(e, w)</code>：仅在 <code>newest</code> 中出现，共 6 次。</li>
        </ul>
      </li>
